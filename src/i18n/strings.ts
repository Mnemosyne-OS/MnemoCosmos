/**
 * strings.ts — everything this cartridge says, in every language it says it in.
 *
 * The host broadcasts its language over the bridge (`onHostConfig`), so the
 * cartridge follows the app rather than asking again. A key missing from a
 * locale falls back to English key by key, which is the normal thing for an
 * interface: a half-English toolbar is untidy, not wrong.
 *
 * 🚨 That is NOT true of the OBJECT names. A question offering four objects
 * where two are named in French and two in English hands the answer to anyone
 * who notices. Object names come from the catalogue and from the constellation
 * file, and those are governed separately — a catalogue designation like
 * `NGC 224` is the same string in every language, which is exactly why this
 * cartridge keys everything on it.
 *
 * Adding a language is a data change: fill a block, nothing else moves.
 */

